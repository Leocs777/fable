// 高风险关键词预筛（入口拦截的轻量第一道；正式版应有更完整的安全分类器）
export const CRISIS_PATTERNS = [
  "自杀", "自残", "轻生", "不想活", "活不下去", "结束生命", "伤害自己",
  "suicide", "kill myself", "self-harm", "end my life", "want to die",
];

export const HIGH_RISK_PATTERNS = [
  "癌症", "确诊", "治疗", "吃药", "停药", "手术", "化疗", "病情", "诊断",
  "起诉", "打官司", "坐牢", "判刑", "赌", "杠杆", "梭哈", "借钱炒", "all in",
  "diagnosis", "lawsuit", "cancer", "medication", "gambling",
];

export function classifyRisk(question) {
  const text = (question || "").toLowerCase();
  const raw = question || "";
  if (CRISIS_PATTERNS.some((p) => raw.includes(p) || text.includes(p.toLowerCase()))) {
    return "crisis";
  }
  if (HIGH_RISK_PATTERNS.some((p) => raw.includes(p) || text.includes(p.toLowerCase()))) {
    return "high_risk";
  }
  return "allowed";
}
